// El de una REGION se arma al vuelo: su nombre ya existe en REGIONS y no
// se traduce (es un nombre propio), asi que escribirlos otra vez solo
// seria otra copia que se desincroniza.
static const char *medalRegion(int i, bool corto) {
  // DOS buffers, uno por longitud. Con uno solo, pedir la etiqueta y
  // despues la descripcion del mismo logro devolvia dos punteros al
  // MISMO sitio: el segundo pisaba al primero y la etiqueta salia
  // "BEAT KANTO" (10 letras donde caben 6). Lo caza
  // `las_medallas_estan_en_todos_los_idiomas`, que se guarda los tres
  // punteros antes de medirlos —— que es justo lo que hace la pantalla.
  static char corto_[16], largo_[24];
  const char *r = regionAt((uint8_t)(i - MED_REGION0)).name;
  if (corto) { snprintf(corto_, sizeof(corto_), "%s", r); return corto_; }
  snprintf(largo_, sizeof(largo_), "BEAT %s", r);
  return largo_;
}

const char *medalName(int i) {
  if (i < 0 || i >= MED_COUNT) return "";
  if (i < MED_TRANSLATED) return MED_NAME[gLang][i];
  if (i >= MED_REGION0) return medalRegion(i, false);
  return MED_X_DSC[i - MED_TRANSLATED];
}
const char *medalLabel(int i) {
  if (i < 0 || i >= MED_COUNT) return "";
  if (i < MED_TRANSLATED) return MED_LBL[gLang][i];
  if (i >= MED_REGION0) return medalRegion(i, true);
  return MED_X_LBL[i - MED_TRANSLATED];
}
const char *medalDesc(int i) {
  if (i < 0 || i >= MED_COUNT) return "";
  if (i < MED_TRANSLATED) return MED_DSC[gLang][i];
  if (i >= MED_REGION0) return medalRegion(i, false);
  return MED_X_DSC[i - MED_TRANSLATED];
}

void loadLang() {
  Preferences p;
  p.begin("tamapoke", true);  // solo lectura
  uint8_t v = p.getUChar("lang", LANG_DEFAULT);
  p.end();
  gLang = (v < LANG_COUNT) ? (Lang)v : LANG_DEFAULT;
}

void setLang(Lang l) {
  if (l >= LANG_COUNT) return;
  gLang = l;
  Preferences p;
  p.begin("tamapoke", false);
  p.putUChar("lang", (uint8_t)l);
  p.end();
}
