static inline const char *itemName(uint8_t i) {
  if (i >= ITEM_COUNT) i = 0;
  switch (gLang) {
    case LANG_ES: return ITEM_NAME_ES[i];
    case LANG_FR: return ITEM_NAME_FR[i];
    case LANG_DE: return ITEM_NAME_DE[i];
    case LANG_IT: return ITEM_NAME_IT[i];
    case LANG_PT: return ITEM_NAME_PT[i];
    case LANG_JA: return ITEM_NAME_JA[i];
    case LANG_KO: return ITEM_NAME_KO[i];
    default: return ITEM_TBL[i].name;
  }
}

static inline const char *itemDesc(uint8_t i) {
  if (i >= ITEM_COUNT) return "";
  const char *s = nullptr;
  switch (gLang) {
    case LANG_ES: s = ITEM_DESC_ES[i]; break;
    case LANG_FR: s = ITEM_DESC_FR[i]; break;
    case LANG_DE: s = ITEM_DESC_DE[i]; break;
    case LANG_IT: s = ITEM_DESC_IT[i]; break;
    case LANG_PT: s = ITEM_DESC_PT[i]; break;
    case LANG_JA: s = ITEM_DESC_JA[i]; break;
    case LANG_KO: s = ITEM_DESC_KO[i]; break;
    default: break;
  }
  return s ? s : ITEM_DESC[i];
}
